/** 仅拦截明确声称已经暂存的答复；讨论、计划和失败说明不触发写操作。 */
export function claimsStagedChanges(text: string): boolean {
  return text.split(/[。！？!?\n]/).some((sentence) => {
    if (/(?:尚未|并未|未能|未曾|未(?:生成|创建|提交|保存|暂存|写入|完成)|没有|无法|不能|不会|不要|不应|假如|如果|例如|比如)/.test(sentence)) return false
    return /(?:已经|现已|已)(?:为你|为您)?(?:成功)?(?:暂存|提交.{0,12}(?:审阅|变更)|(?:生成|创建|保存|添加|放入|加入|完成).{0,32}(?:暂存|待审阅|待确认|变更))/.test(sentence)
      || /(?:已经|现已|已)(?:将|把).{0,32}(?:暂存|待审阅|待确认)/.test(sentence)
      || /(?:暂存区|待审阅区).{0,12}(?:已|已经)(?:有|新增|包含)/.test(sentence)
  })
}

